import { Slide, Language, AudienceType } from '../types';
import { getCleanImageUrl } from './imageService';

export function getFallbackPresentation(
  topic: string,
  lang: Language,
  count: number,
  audience: AudienceType
): Slide[] {
  const slides: Slide[] = [];

  // Title Slide
  slides.push({
    id: 'slide-1',
    layout: 'title',
    title: topic,
    subtitle: lang === 'uz' 
      ? 'Sun\'iy intellekt tomonidan yaratilgan professional taqdimot' 
      : lang === 'ru' 
      ? 'Профессиональная презентация, созданная искусственным интеллектом' 
      : 'Professional presentation generated by Artificial Intelligence',
    badge: lang === 'uz' ? 'Taqdimot' : lang === 'ru' ? 'Презентация' : 'Presentation',
    imageUrl: getCleanImageUrl(topic, 'cover', 0),
    showImage: true,
    selected: true,
    speakerNotes: lang === 'uz'
      ? `Hurmatli tinglovchilar, bugun biz "${topic}" mavzusini batafsil ko'rib chiqamiz.`
      : lang === 'ru'
      ? `Уважаемые слушатели, сегодня мы детально рассмотрим тему "${topic}".`
      : `Welcome everyone, today we will dive deep into "${topic}".`
  });

  // Slide 2: Bullets / Overview
  slides.push({
    id: 'slide-2',
    layout: 'bullets',
    title: lang === 'uz' ? 'Kirish va Dolzarblik' : lang === 'ru' ? 'Введение и Актуальность' : 'Introduction & Overview',
    subtitle: lang === 'uz' ? 'Mavzuning asosiy ahamiyati va ko\'lami' : lang === 'ru' ? 'Ключевое значение и охват темы' : 'Key importance and context',
    badge: '01',
    imageUrl: getCleanImageUrl(topic, 'overview', 1),
    showImage: true,
    selected: true,
    points: lang === 'uz' ? [
      `${topic} sohasidagi zamonaviy tendentsiyalar va jadal o'sish sur'atlari`,
      'Zamonaviy texnologiyalar va yangi yondashuvlarning amaliy hayotga tatbiqi',
      'Ushbu yo\'nalishda uchraydigan asosiy qiyinchiliklar va yechimlar',
      'Kelajak istiqbollari va strategik imkoniyatlar'
    ] : lang === 'ru' ? [
      `Современные тенденции и темпы роста в области "${topic}"`,
      'Применение передовых технологий и методологий на практике',
      'Ключевые вызовы и практические пути их преодоления',
      'Перспективы дальнейшего развития и новые возможности'
    ] : [
      `Current trends and rapid growth trajectories in ${topic}`,
      'Real-world implementation of modern technologies and methodologies',
      'Overcoming foundational challenges with innovative solutions',
      'Future strategic outlook and high-value opportunities'
    ],
    speakerNotes: lang === 'uz' ? 'Bu slaydda mavzuning nima uchun hozirda muhimligi ta\'kidlanadi.' : 'Here we establish the core importance and context.'
  });

  // Slide 3: Stats
  if (count >= 3) {
    slides.push({
      id: 'slide-3',
      layout: 'stats',
      title: lang === 'uz' ? 'Asosiy Ko\'rsatkichlar va Faktlar' : lang === 'ru' ? 'Ключевые Показатели и Цифры' : 'Key Metrics & Data Points',
      subtitle: lang === 'uz' ? 'Raqamlar va tahliliy ma\'lumotlar' : lang === 'ru' ? 'Цифровой анализ и статистика' : 'Measurable impact and analysis',
      badge: '02',
      imageUrl: getCleanImageUrl(topic, 'statistics', 2),
      showImage: false,
      selected: true,
      stats: lang === 'uz' ? [
        { value: '+85%', label: 'Samaradorlik o\'sishi', trend: 'Yillik ko\'rsatkich' },
        { value: '3.4x', label: 'Jarayon tezlashuvi', trend: 'Avtomatlashtirish hisobiga' },
        { value: '92%', label: 'Ijobiy natija', trend: 'Foydalanuvchilar qoniqishi' }
      ] : lang === 'ru' ? [
        { value: '+85%', label: 'Рост эффективности', trend: 'Годовой показатель' },
        { value: '3.4x', label: 'Ускорение процессов', trend: 'За счет оптимизации' },
        { value: '92%', label: 'Положительный итог', trend: 'Удовлетворенность клиентов' }
      ] : [
        { value: '+85%', label: 'Efficiency Boost', trend: 'Year-over-year' },
        { value: '3.4x', label: 'Process Acceleration', trend: 'Through optimization' },
        { value: '92%', label: 'Success Rate', trend: 'User satisfaction' }
      ]
    });
  }

  // Slide 4: Comparison
  if (count >= 4) {
    slides.push({
      id: 'slide-4',
      layout: 'compare',
      title: lang === 'uz' ? 'An\'anaviy va Zamonaviy Yondashuv' : lang === 'ru' ? 'Традиционный vs Современный Подход' : 'Traditional vs Modern Approach',
      subtitle: lang === 'uz' ? 'Ikkala usulning o\'zaro qiyosiy tahlili' : lang === 'ru' ? 'Сравнительный анализ двух методов' : 'Comparative analysis of methodologies',
      badge: '03',
      imageUrl: getCleanImageUrl(topic, 'comparison', 3),
      showImage: false,
      selected: true,
      compare: lang === 'uz' ? {
        leftTitle: 'Avvalgi (Eski) Usul',
        leftItems: [
          'Ko\'p vaqt va mehnat talab qiluvchi qo\'l mehnati',
          'Cheklangan ma\'lumotlar va sekin qaror qabul qilish',
          'Yuqori xatolar ehtimoli va monitoring qiyinligi'
        ],
        rightTitle: 'Zamonaviy (Yangi) Usul',
        rightItems: [
          'Sun\'iy intellekt va avtomatlashgan tezkor tizimlar',
          'Katta ma\'lumotlar tahliliga asoslangan aniq xulosalar',
          'Yuqori aniqlik, tejamkorlik va moslashuvchanlik'
        ]
      } : lang === 'ru' ? {
        leftTitle: 'Традиционный подход',
        leftItems: [
          'Ручные процессы, требующие много времени',
          'Ограниченная аналитика и медленные решения',
          'Высокий риск человеческого фактора'
        ],
        rightTitle: 'Современный подход',
        rightItems: [
          'Автоматизация и технологии искусственного интеллекта',
          'Принятие решений на основе больших данных',
          'Высокая точность, масштабируемость и гибкость'
        ]
      } : {
        leftTitle: 'Legacy Approach',
        leftItems: [
          'Time-consuming manual workflows',
          'Limited data visibility and slow decision making',
          'Higher margin for human error'
        ],
        rightTitle: 'Modern Innovation',
        rightItems: [
          'AI-assisted automated execution',
          'Data-driven insights with predictive clarity',
          'High precision, agility, and cost-efficiency'
        ]
      }
    });
  }

  // Slide 5: Timeline
  if (count >= 5) {
    slides.push({
      id: 'slide-5',
      layout: 'timeline',
      title: lang === 'uz' ? 'Amalga Oshirish Bosqichlari' : lang === 'ru' ? 'Этапы Реализации' : 'Implementation Roadmap',
      subtitle: lang === 'uz' ? 'Qadamba-qadam harakatlar rejasi' : lang === 'ru' ? 'Пошаговый план внедрения' : 'Step-by-step phased execution',
      badge: '04',
      imageUrl: getCleanImageUrl(topic, 'timeline', 4),
      showImage: false,
      selected: true,
      timeline: lang === 'uz' ? [
        { step: '01', title: 'Tadqiqot va Tahlil', description: 'Bozor va mavjud holatni to\'liq o\'rganish, maqsadlarni belgilash.' },
        { step: '02', title: 'Loyihalash', description: 'Optimal arxitektura va strategiyani shakllantirish.' },
        { step: '03', title: 'Amaliyotga joriy etish', description: 'Sinovdan o\'tkazish va jarayonlarni ishga tushirish.' },
        { step: '04', title: 'Masshtablash', description: 'Natijalarni tahlil qilish va doimiy takomillashtirish.' }
      ] : lang === 'ru' ? [
        { step: '01', title: 'Исследование и анализ', description: 'Аудит текущей ситуации и постановка четких целей.' },
        { step: '02', title: 'Проектирование', description: 'Разработка оптимальной архитектуры и дорожной карты.' },
        { step: '03', title: 'Внедрение', description: 'Тестирование, запуск и интеграция процессов.' },
        { step: '04', title: 'Масштабирование', description: 'Оптимизация результатов и непрерывное улучшение.' }
      ] : [
        { step: '01', title: 'Discovery & Analysis', description: 'Thorough assessment of landscape and goal alignment.' },
        { step: '02', title: 'Architecture Design', description: 'Formulating strategic frameworks and execution models.' },
        { step: '03', title: 'Deployment & Rollout', description: 'Pilot testing and full integration into workflows.' },
        { step: '04', title: 'Scale & Optimization', description: 'Evaluating feedback and continuous refinement.' }
      ]
    });
  }

  // Slide 6: Quote (if count >= 6)
  if (count >= 6) {
    slides.push({
      id: 'slide-6',
      layout: 'quote',
      title: lang === 'uz' ? 'Asosiy Fikr' : lang === 'ru' ? 'Ключевая Мысль' : 'Guiding Vision',
      badge: '05',
      imageUrl: getCleanImageUrl(topic, 'vision', 5),
      showImage: false,
      selected: true,
      quote: lang === 'uz' ? {
        text: 'Kelajak bugun qanday qadamlar qo\'yishimizga bog\'liq. Innovatsiyani qabul qilganlar g\'alaba qozonadi.',
        author: 'Innovatsiya Qoidasi',
        role: 'Zamonaviy Taraqqiyot'
      } : lang === 'ru' ? {
        text: 'Будущее зависит от того, какие решения мы принимаем сегодня. Побеждает тот, кто не боится инноваций.',
        author: 'Принцип Развития',
        role: 'Современный мир'
      } : {
        text: 'The best way to predict the future is to create it through relentless innovation and decisive action.',
        author: 'Leadership Insight',
        role: 'Modern Innovation'
      }
    });
  }

  // Slide 7 (if count >= 7): Extra bullets
  if (count >= 7) {
    slides.push({
      id: 'slide-7',
      layout: 'bullets',
      title: lang === 'uz' ? 'Kutilayotgan Natijalar' : lang === 'ru' ? 'Ожидаемые Результаты' : 'Key Expected Outcomes',
      subtitle: lang === 'uz' ? 'Strategik maqsadlarga erishish mezonlari' : lang === 'ru' ? 'Критерии достижения успеха' : 'Strategic milestones and value created',
      badge: '06',
      imageUrl: getCleanImageUrl(topic, 'results', 6),
      showImage: true,
      selected: true,
      points: lang === 'uz' ? [
        'Resurslarni 40% gacha tejash va xarajatlarni optimallashtirish',
        'Jamoa va tizim o\'rtasidagi hamkorlik sifatini oshirish',
        'Uzoq muddatli barqarorlik va raqobatbardoshlikni ta\'minlash',
        'Yangi bozorlar va imkoniyatlar eshigini ochish'
      ] : lang === 'ru' ? [
        'Экономия ресурсов до 40% и оптимизация операционных затрат',
        'Повышение качества взаимодействия между участниками процесса',
        'Обеспечение долгосрочной устойчивости и конкурентоспособности',
        'Выход на новые рынки и освоение новых возможностей'
      ] : [
        'Up to 40% resource conservation and budget optimization',
        'Elevated collaboration and synergy across stakeholders',
        'Sustainable long-term competitive advantage',
        'Unlocking new market horizons and scalable avenues'
      ]
    });
  }

  // Final Slide: Conclusion
  slides.push({
    id: `slide-${slides.length + 1}`,
    layout: 'conclusion',
    title: lang === 'uz' ? 'Xulosa va Keyingi Qadamlar' : lang === 'ru' ? 'Заключение и Следующие Шаги' : 'Conclusion & Next Steps',
    subtitle: lang === 'uz' ? 'E\'tiboringiz uchun rahmat!' : lang === 'ru' ? 'Спасибо за внимание!' : 'Thank you for your attention!',
    badge: 'Xulosa',
    imageUrl: getCleanImageUrl(topic, 'conclusion', 7),
    showImage: true,
    selected: true,
    conclusion: lang === 'uz' ? {
      mainMessage: `"${topic}" mavzusi bugungi kunda har qachongidan ham dolzarb bo'lib, yangi imkoniyatlar eshigini ochadi.`,
      takeaways: [
        'Innovatsion usullarni qo\'llash orqali yuqori natijaga erishish mumkin',
        'Doimiy o\'rganish va amaliyotga tatbiq etish muvaffaqiyat garovidir',
        'Hamkorlik va to\'g\'ri rejalashtirish hal qiluvchi ahamiyatga ega'
      ],
      callToAction: 'Savollaringiz bormi? Muhokamaga marhamat!',
      contact: 'Aloqa: info@slaydai.uz'
    } : lang === 'ru' ? {
      mainMessage: `Тема "${topic}" открывает колоссальные возможности для трансформации и роста в современных условиях.`,
      takeaways: [
        'Применение инноваций обеспечивает кратный рост результативности',
        'Постоянное обучение и адаптация — ключ к долгосрочному лидерству',
        'Четкая стратегия и партнерство гарантируют успех проекта'
      ],
      callToAction: 'Есть вопросы? Будем рады обсудить!',
      contact: 'Связь: info@slaydai.uz'
    } : {
      mainMessage: `Mastering "${topic}" unlocks unprecedented growth vectors and operational excellence in today\'s landscape.`,
      takeaways: [
        'Leveraging cutting-edge methodologies accelerates breakthroughs',
        'Continuous adaptation and agile execution form the foundation of success',
        'Strategic clarity and cross-functional alignment ensure victory'
      ],
      callToAction: 'Questions & Discussion are welcome!',
      contact: 'Contact: info@slaydai.uz'
    }
  });

  return slides.slice(0, count);
}
